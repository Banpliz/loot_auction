import { Telegraf, Markup } from 'telegraf';

const INSTRUCTIONS = `📋 Как пользоваться ботом

1. Жми «Открыть» — попадёшь в мини-приложение.
2. Впиши свой игровой ник (один раз) — после этого заявка уходит на одобрение админу. Пока не одобрят, доступа к лотам не будет.
3. Как одобрят — открывай вкладку «Лоты»: там список трофеев с текущего ивента.
4. Перед стартом будет обратный отсчёт «Аукцион начнётся через…» — держи вкладку открытой, лоты появятся сами, ничего обновлять руками не нужно.
5. Жми «Ставка», чтобы подать заявку на лот — это не бронь, а участие в розыгрыше среди всех подавших заявку.
6. Пока приём заявок не закончился, заявку можно отменить кнопкой «Отменить».
7. Когда приём заявок закончится, лоты разыгрываются случайно среди подавших заявку. Лоты, на которые никто не заявился, уходят в «Свободные» внизу списка — забрать их в приложении уже нельзя, за них бьются по правилам аукциона прямо в игре.`;

export function createBot(botToken: string, miniAppUrl: string) {
  const bot = new Telegraf(botToken);
  bot.start((ctx) =>
    ctx.reply(
      'Открыть аукцион лута',
      Markup.inlineKeyboard([[Markup.button.webApp('Открыть', miniAppUrl), Markup.button.callback('Инструкция', 'instructions')]])
    )
  );
  bot.action('instructions', async (ctx) => {
    await ctx.answerCbQuery();
    await ctx.reply(INSTRUCTIONS);
  });
  return bot;
}
